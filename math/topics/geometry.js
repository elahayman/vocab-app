// ---------- congruence ----------
// Two triangles ABC and DEF (D↔A, E↔B, F↔C). marks: [['s', 'AB', ticks] or ['a', 'A', arcs]].
function congFig(marks, { mirror = R.coin(), scale = 1 } = {}) {
  const A = [20, 165], B = [135, 165], C = [R.int(35, 95), R.int(45, 70)];
  const P1 = [A, B, C];
  let P2 = P1.map(p => (mirror ? [325 - p[0], p[1]] : [p[0] + 168, p[1]]));
  if (scale !== 1) { const c = cen(...P2); P2 = P2.map(p => [c[0] + (p[0] - c[0]) * scale, c[1] + (p[1] - c[1]) * scale + 15]); }
  const draw = (P, names) => {
    const idx = l => 'ABC'.indexOf(l);
    let s = '';
    marks.forEach(([kind, what, n]) => {
      if (kind === 's') s += ticks(P[idx(what[0])], P[idx(what[1])], n);
      else { const i = idx(what); s += ang(P[i], P[(i + 1) % 3], P[(i + 2) % 3], { n, r: 15, cls: 'hi' }); }
    });
    return tri(P, names, s);
  };
  return svg(draw(P1, ['A', 'B', 'C']) + draw(P2, ['D', 'E', 'F']), 195);
}

