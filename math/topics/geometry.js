// Two parallel lines and a transversal; T1 on the top line, T2 on the bottom one.
function parallelFig(pairType, labels, mirror) {
  const X = p => (mirror ? [320 - p[0], p[1]] : p);
  const T1 = [200, 60], T2 = [130, 140];
  const u = D.unit(D.sub(T1, T2));
  const E1 = [300, 60], W1 = [20, 60], E2 = [300, 140], W2 = [20, 140];
  const U1 = D.add(T1, u, 40), D1 = D.add(T1, u, -40), U2 = D.add(T2, u, 40);
  let s = seg(X(W1), X(E1)) + seg(X(W2), X(E2)) + seg(X(D.add(T2, u, -42)), X(D.add(T1, u, 42))) +
    par(X([60, 60]), X([80, 60])) + par(X([60, 140]), X([80, 140]));
  const pairs = {
    corr: [[T1, E1, U1], [T2, E2, U2]],
    alt: [[T1, W1, D1], [T2, E2, U2]],
    vert: [[T1, E1, U1], [T1, W1, D1]],
    adj: [[T1, E1, U1], [T1, U1, W1]],
  }[pairType];
  pairs.forEach(([v, a, b], i) => { s += ang(X(v), X(a), X(b), { t: labels[i], cls: i ? 'q' : '' }); });
  return svg(s, 200);
}

