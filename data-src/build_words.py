"""Builds words.js from the shared word bank spreadsheet + sentence files."""
import json, glob, re, sys, openpyxl
from pathlib import Path
here = Path(__file__).resolve().parent
xlsx = sys.argv[1] if len(sys.argv) > 1 else '/mnt/project-files/word-bank/מאגר_מילים_אנגלית.xlsx'
wb = openpyxl.load_workbook(xlsx, read_only=True)
rows = list(wb['מאגר משותף'].iter_rows(values_only=True))[1:]
sent = {}
for fn in sorted(here.glob('sentences*.txt')):
    for line in open(fn, encoding='utf8'):
        if '|' in line:
            i, s = line.rstrip('\n').split('|', 1)
            sent[int(i)] = s
cats = sorted({r[3] for r in rows})
words = []
for r in rows:
    if not r[0] or not r[1]:
        continue
    wid = int(r[0])
    stage = int(str(r[4]).strip()[0])
    words.append([wid, r[1].strip(), r[2].strip(), cats.index(r[3]), stage,
                  1 if r[7] == 'כן' else 0, sent.get(wid, '')])
sys.path.insert(0, str(here))
from morphology import AFFIXES, PAIRS, HE
known = {w[1].lower(): w for w in words}
# [derived, affix, base, hebrew of derived]; kept when either side is in the bank and we can show a meaning.
family = []
for d, (aff, base) in PAIRS.items():
    he = known[d][2] if d in known else HE.get(d)
    if he and (d in known or base in known):
        family.append([d, aff, base, he])
out = here.parent / 'words.js'
out.write_text('// Generated by data-src/build_words.py. Do not edit by hand.\n'
               '// [id, english, hebrew, categoryIndex, stage, veryBasic, sentence]\n'
               'window.CATEGORIES = ' + json.dumps(cats, ensure_ascii=False) + ';\n'
               'window.WORDS = ' + json.dumps(words, ensure_ascii=False, separators=(',', ':')) + ';\n'
               '// Word families: [derived, affix, base, hebrew]\n'
               'window.AFFIXES = ' + json.dumps(AFFIXES, ensure_ascii=False) + ';\n'
               'window.FAMILY = ' + json.dumps(family, ensure_ascii=False, separators=(',', ':')) + ';\n',
               encoding='utf8')
print(len(words), 'words ->', out)
